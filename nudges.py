def pick(kind: str, user_id: int, day: date = None, **values) -> str:
    """Фраза группы kind: меняется каждый день и у разных людей разная.
    Пользовательские значения (план, имя) экранируются для HTML."""
    pool = LINES[kind]
    day = day or date.today()
    text = pool[(day.toordinal() + user_id) % len(pool)]
    values = {k: html.escape(str(v)) for k, v in values.items()}
    return text.format(**values)


def mascot_name(user: dict) -> str:
    kind = game.LEGACY_MASCOTS.get(user.get("mascot"), user.get("mascot")) or "cat-purple"
    return MASCOT_NAMES.get(kind, "Сирень")


def hours_to_midnight(user: dict) -> int:
    now = game.local_now(user)
    return max(1, 24 - now.hour)


def days_away(user: dict, today: date) -> int:
    """Сколько дней не было активности (квест или открытие приложения). 0 — если неизвестно."""
    seen = []
    if user.get("streak_last_date"):
        seen.append(user["streak_last_date"][:10])
    if user.get("last_seen_at"):
        seen.append(str(user["last_seen_at"])[:10])
    if not seen:
        return 0
    try:
        last = datetime.strptime(max(seen), "%Y-%m-%d").date()
    except ValueError:
        return 0
    return max(0, (today - last).days)


def context(user_id: int) -> dict:
    """Всё, что нужно для подстановки в фразы."""
    user = storage.get_user(user_id)
    today = game.local_today(user)
    streak = game.streak_view(user.get("streak_current"), user.get("streak_best"),
                              user.get("streak_last_date"), user.get("freeze_week"), today)
    return {
        "user": user, "today": today, "m": mascot_name(user),
        "hours": hours_to_midnight(user), "streak": streak, "away": days_away(user, today),
    }
