PACK_BY_ID = {p[0]: p for p in PACKS}


def quest_id(pack: str, n: int) -> str:
    return f"pack_{pack}_{n + 1}"


def catalog_entries() -> dict:
    out = {}
    for pid, _emoji, _name, _about, mode, _season in PACKS:
        for n, (emoji, title, text) in enumerate(QUESTS[pid]):
            qid = quest_id(pid, n)
            out[qid] = {
                "id": qid, "mode": mode, "sphere": None, "emoji": emoji, "title": title, "text": text,
                "tiers": {"medium": text}, "why": None, "outcome": None,
                "pack": pid, "pack_index": n,
            }
    return out


def in_season(pack: str, today: date) -> bool:
    season = PACK_BY_ID[pack][5]
    if not season:
        return True
    start, end = season
    md = (today.month, today.day)
    if start <= end:
        return start <= md <= end
    return md >= start or md <= end  # сезон через Новый год


def season_end(pack: str):
    season = PACK_BY_ID[pack][5]
    return f"{season[1][1]:02d}.{season[1][0]:02d}" if season else None


def locked(q: dict, premium: bool) -> bool:
    return bool(q.get("pack")) and q["pack_index"] >= FREE_PER_PACK and not premium
