HEARTS = ["❤️", "💖", "💗", "💕", "🩷", "💞", "💘", "🤍", "💓", "🫶"]

GREETINGS = ["Доброе утро", "С добрым утром", "Привет, красавица", "Утро доброе", "Просыпайся, солнышко"]


def for_day(day_number: int) -> str:
    """Комплимент на день: перемешанный круг без повторов, сердечко в конце."""
    n = len(COMPLIMENTS)
    cycle, pos = divmod(day_number, n)
    order = list(range(n))
    random.Random(cycle).shuffle(order)
    text = COMPLIMENTS[order[pos]]
    heart = HEARTS[day_number % len(HEARTS)]
    greet = GREETINGS[day_number % len(GREETINGS)]
    if text.startswith("Доброе утро"):
        return f"{text} {heart}"
    return f"{greet}! ☀️\n\n{text} {heart}"
